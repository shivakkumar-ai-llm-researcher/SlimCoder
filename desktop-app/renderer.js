const { ipcRenderer } = require('electron');
const marked = require('marked');
const createDOMPurify = require('dompurify');
const DOMPurify = createDOMPurify(window);


// Window Controls
document.getElementById('min-btn').addEventListener('click', () => ipcRenderer.send('window-minimize'));
document.getElementById('max-btn').addEventListener('click', () => ipcRenderer.send('window-maximize'));
document.getElementById('close-btn').addEventListener('click', () => ipcRenderer.send('window-close'));

const promptInput = document.getElementById('prompt-input');
const sendBtn = document.getElementById('send-btn');
const messagesContainer = document.getElementById('messages-container');

// Focus input on load
window.addEventListener('DOMContentLoaded', () => {
    promptInput.focus();
});

// Auto-resize textarea
promptInput.addEventListener('input', function() {
    this.style.height = 'auto';
    this.style.height = (this.scrollHeight) + 'px';
    if(this.value.trim() === '') {
        sendBtn.disabled = true;
    } else {
        sendBtn.disabled = false;
    }
});

// Send message on Enter (without shift)
promptInput.addEventListener('keydown', (e) => {
    if (e.key === 'Enter' && !e.shiftKey) {
        e.preventDefault();
        sendMessage();
    }
});

sendBtn.addEventListener('click', sendMessage);

// Suggestion chips
document.querySelectorAll('.chip').forEach(chip => {
    chip.addEventListener('click', () => {
        promptInput.value = chip.dataset.prompt;
        sendBtn.disabled = false;
        sendMessage();
    });
});

async function sendMessage() {
    const text = promptInput.value.trim();
    if (!text) return;

    // Add user message to UI
    appendMessage('user', text);
    promptInput.value = '';
    promptInput.style.height = 'auto';
    sendBtn.disabled = true;

    // Show loading indicator
    const loadingId = appendLoadingIndicator();

    // Update state badge to reflect generation processing
    const stateBadge = document.getElementById("current-state-badge");
    if (stateBadge) {
        stateBadge.innerText = "ROUTING ORCHESTRATION...";
        stateBadge.className = "badge active";
    }

    // Get selected stacks
    const frontend = document.getElementById('frontend-stack').value;
    const backend = document.getElementById('backend-stack').value;

    try {
        // Send to local SLM
        const response = await fetch('http://127.0.0.1:8081/generate', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
                task: text,
                frontend_stack: frontend || null,
                backend_stack: backend || null
            })
        });

        if (!response.ok) throw new Error(`HTTP error! status: ${response.status}`);
        const data = await response.json();
        
        // Remove loading indicator
        removeMessage(loadingId);

        // Format output
        let content = '';
        if (data.domains_used && data.domains_used.length > 0) {
            content += `**Generated by:** \`${data.domains_used.join(', ')}\`\n\n`;
        }
        content += data.code;

        appendMessage('assistant', content);
    } catch (error) {
        removeMessage(loadingId);
        appendMessage('assistant', `**Connection Error:** Could not connect to local SLM server at http://127.0.0.1:8081.\n\nPlease ensure your Python backend (\`server.py\`) is running.`);
    }
}

function appendMessage(role, content) {
    const id = 'msg-' + Date.now();
    const div = document.createElement('div');
    div.className = `message ${role}-message`;
    div.id = id;

    const avatar = document.createElement('div');
    avatar.className = 'message-avatar';
    if (role === 'user') {
        avatar.innerHTML = '<div class="user-avatar">U</div>';
    } else {
        avatar.innerHTML = '<div class="logo-icon-small"></div>';
    }

    const msgContent = document.createElement('div');
    msgContent.className = 'message-content';
    
    // Parse markdown securely
    if (role === 'assistant') {
        const rawHtml = marked.parse(content);
        const cleanHtml = DOMPurify.sanitize(rawHtml);
        msgContent.innerHTML = cleanHtml;
    } else {
        msgContent.innerText = content;
    }

    div.appendChild(avatar);
    div.appendChild(msgContent);

    // Hide welcome message if present
    const welcome = document.querySelector('.welcome-message');
    if (welcome) welcome.style.display = 'none';

    messagesContainer.appendChild(div);
    messagesContainer.scrollTo({ top: messagesContainer.scrollHeight, behavior: 'smooth' });
    
    return id;
}

function appendLoadingIndicator() {
    const id = 'msg-' + Date.now();
    const div = document.createElement('div');
    div.className = `message assistant-message`;
    div.id = id;

    const avatar = document.createElement('div');
    avatar.className = 'message-avatar';
    avatar.innerHTML = '<div class="logo-icon-small"></div>';

    const msgContent = document.createElement('div');
    msgContent.className = 'message-content';
    msgContent.innerHTML = `
        <div class="typing-indicator">
            <div class="typing-dot"></div>
            <div class="typing-dot"></div>
            <div class="typing-dot"></div>
        </div>
    `;

    div.appendChild(avatar);
    div.appendChild(msgContent);
    messagesContainer.appendChild(div);
    messagesContainer.scrollTo({ top: messagesContainer.scrollHeight, behavior: 'smooth' });
    
    return id;
}

function removeMessage(id) {
    const el = document.getElementById(id);
    if (el) el.remove();
}

const BACKEND_URL = "http://127.0.0.1:8081/api/logs";

function startLogStreaming() {
    const terminal = document.getElementById("log-terminal");
    const stateBadge = document.getElementById("current-state-badge");

    setInterval(async () => {
        try {
            const response = await fetch(`${BACKEND_URL}?lines=20`);
            const data = await response.json();

            if (data.status === "active" && data.logs.length > 0) {
                // Clear the console view block for fresh incoming paint ticks
                terminal.innerHTML = "";

                data.logs.forEach(logString => {
                    try {
                        // Parse the custom structural JSON logs we configured
                        const logObj = JSON.parse(logString);
                        
                        const row = document.createElement("div");
                        row.className = `log-row ${logObj.level}`;
                        row.innerHTML = `[${logObj.timestamp}] [${logObj.module.toUpperCase()}]: ${logObj.message}`;
                        terminal.appendChild(row);

                        // Dynamic HUD state badge update logic
                        if (logObj.message.includes("INITIATING") || logObj.message.includes("SURGERY") || logObj.message.includes("PROMPTING")) {
                            stateBadge.innerText = "ENGINE ACTIVE";
                            stateBadge.className = "badge active";
                        } else if (logObj.message.includes("SUCCESS")) {
                            stateBadge.innerText = "CORE ACTIVE / IDLE";
                            stateBadge.className = "badge idle";
                        }
                    } catch (e) {
                        // Fallback handling if a raw text string slips into the log file
                        const rawRow = document.createElement("div");
                        rawRow.className = "log-row";
                        rawRow.innerText = logString;
                        terminal.appendChild(rawRow);
                    }
                });

                // Auto Scroll down to the absolute bottom of the terminal view block
                terminal.scrollTop = terminal.scrollHeight;
            }
        } catch (error) {
            console.error("Dashboard failed to fetch orchestrator stream logs:", error);
        }
    }, 800); // Polling interval set to 800ms for fast feedback with low CPU load
}

// Start tracking immediately upon interface boot
document.addEventListener("DOMContentLoaded", startLogStreaming);
